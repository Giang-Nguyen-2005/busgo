CREATE TABLE support_tickets (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,
 booking_id BIGINT NOT NULL,
 customer_id BIGINT NOT NULL,
 operator_id BIGINT NOT NULL,
 category VARCHAR(40) NOT NULL,
 subject VARCHAR(160) NOT NULL,
 status VARCHAR(30) NOT NULL DEFAULT 'OPEN',
 escalation VARCHAR(30) NOT NULL DEFAULT 'NONE',
 priority VARCHAR(10) NOT NULL DEFAULT 'NORMAL',
 assigned_user_id BIGINT NULL,
 resolved_by BIGINT NULL,
 resolved_by_admin BOOLEAN NOT NULL DEFAULT FALSE,
 resolved_at DATETIME(6) NULL,
 reopen_count INT NOT NULL DEFAULT 0,
 version BIGINT NOT NULL DEFAULT 0,
 request_key VARCHAR(100) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 request_hash CHAR(64) NOT NULL,
 created_at DATETIME(6) NOT NULL,
 updated_at DATETIME(6) NOT NULL,
 UNIQUE KEY uq_support_request(customer_id,request_key),
 FOREIGN KEY(booking_id) REFERENCES bookings(id),
 FOREIGN KEY(customer_id) REFERENCES users(id),
 FOREIGN KEY(operator_id) REFERENCES transport_operators(id),
 FOREIGN KEY(assigned_user_id) REFERENCES users(id),
 FOREIGN KEY(resolved_by) REFERENCES users(id),
 INDEX ix_support_operator(operator_id,status,created_at,id),
 INDEX ix_support_customer(customer_id,created_at,id),
 INDEX ix_support_assigned(operator_id,assigned_user_id,status,id),
 CHECK(status IN ('OPEN','IN_PROGRESS','WAITING_CUSTOMER','RESOLVED','CLOSED')),
 CHECK(escalation IN ('NONE','OPERATOR_ADMIN','PLATFORM')),
 CHECK(priority IN ('LOW','NORMAL','HIGH')),
 CHECK(reopen_count BETWEEN 0 AND 2),
 CHECK(category IN ('TRIP_INFORMATION','PICKUP_DROPOFF','TICKET_ACCESS','BAGGAGE','BOOKING_HELP','BOOKING_CHANGE_REQUEST','CANCELLATION_HELP','PAYMENT_QUESTION','REFUND_COMPLAINT','SERVICE_COMPLAINT','OTHER'))
);
CREATE TABLE support_activity (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,
 ticket_id BIGINT NOT NULL,
 actor_id BIGINT NOT NULL,
 actor_role VARCHAR(30) NOT NULL,
 event_type VARCHAR(50) NOT NULL,
 visibility VARCHAR(20) NOT NULL,
 content VARCHAR(4000) NOT NULL,
 from_status VARCHAR(30),
 to_status VARCHAR(30),
 assigned_user_id BIGINT NULL,
 created_at DATETIME(6) NOT NULL,
 FOREIGN KEY(ticket_id) REFERENCES support_tickets(id),
 FOREIGN KEY(actor_id) REFERENCES users(id),
 INDEX ix_support_activity(ticket_id,created_at,id),
 CHECK(visibility IN ('PUBLIC','INTERNAL','PLATFORM'))
);
CREATE TABLE support_disputes (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,
 ticket_id BIGINT NOT NULL UNIQUE,
 reason VARCHAR(4000) NOT NULL,
 status VARCHAR(30) NOT NULL DEFAULT 'SUBMITTED',
 outcome VARCHAR(40) NULL,
 decision VARCHAR(4000) NULL,
 decided_by BIGINT NULL,
 decided_at DATETIME(6) NULL,
 created_at DATETIME(6) NOT NULL,
 FOREIGN KEY(ticket_id) REFERENCES support_tickets(id),
 FOREIGN KEY(decided_by) REFERENCES users(id),
 INDEX ix_dispute_queue(status,created_at,id),
 CHECK(status IN ('SUBMITTED','UNDER_REVIEW','WAITING_INFORMATION','CLOSED')),
 CHECK(outcome IS NULL OR outcome IN ('OPERATOR_RESOLUTION_UPHELD','CUSTOMER_COMPLAINT_UPHELD','ADDITIONAL_REVIEW_REQUIRED','INSUFFICIENT_EVIDENCE'))
);
CREATE TABLE support_requests (
 ticket_id BIGINT NOT NULL,
 actor_id BIGINT NOT NULL,
 request_key VARCHAR(100) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 request_hash CHAR(64) NOT NULL,
 PRIMARY KEY(ticket_id,actor_id,request_key),
 FOREIGN KEY(ticket_id) REFERENCES support_tickets(id),
 FOREIGN KEY(actor_id) REFERENCES users(id)
);
CREATE TABLE audit_events (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,
 event_code VARCHAR(80) NOT NULL,
 actor_id BIGINT NOT NULL,
 actor_role VARCHAR(80) NOT NULL,
 operator_id BIGINT NULL,
 resource_type VARCHAR(40) NOT NULL,
 resource_id BIGINT NOT NULL,
 action VARCHAR(80) NOT NULL,
 outcome VARCHAR(20) NOT NULL DEFAULT 'SUCCESS',
 metadata JSON NOT NULL,
 correlation_id VARCHAR(100) NULL,
 created_at DATETIME(6) NOT NULL,
 INDEX ix_audit_operator(operator_id,created_at,id),
 INDEX ix_audit_resource(resource_type,resource_id,created_at,id),
 INDEX ix_audit_code(event_code,created_at,id)
);

CREATE TABLE support_notifications (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,
 recipient_user_id BIGINT NOT NULL,
 operator_id BIGINT NULL,
 audience VARCHAR(20) NOT NULL,
 recipient_key VARCHAR(180) NOT NULL,
 event_key VARCHAR(160) NOT NULL,
 event_type VARCHAR(60) NOT NULL,
 title VARCHAR(200) NOT NULL,
 message VARCHAR(500) NOT NULL,
 booking_id BIGINT NOT NULL,
 booking_code VARCHAR(50) NOT NULL,
 navigation_target VARCHAR(200) NOT NULL,
 read_at DATETIME(6) NULL,
 created_at DATETIME(6) NOT NULL,
 UNIQUE KEY uq_support_notification(recipient_key,event_key),
 INDEX ix_support_inbox(recipient_user_id,audience,operator_id,created_at,id),
 FOREIGN KEY(recipient_user_id) REFERENCES users(id),
 FOREIGN KEY(operator_id) REFERENCES transport_operators(id),
 FOREIGN KEY(booking_id) REFERENCES bookings(id),
 CHECK(audience IN ('CUSTOMER','OPERATOR','PLATFORM'))
);
